#!/bin/sh
# Generates the action language's evaluator for each host (the parser engine
# and the lexer) from src/script_eval.tmpl. Run after editing the template.
set -e
here=$(cd "$(dirname "$0")/.." && pwd)
gen() {
    host=$1
    aux=$2
    out=$3
    shift 3
    {
        echo "// Generated by tools/gen_script_eval.sh from src/script_eval.tmpl for $host; edit the template."
        echo
        echo 'import "abla/text"'
        for i in "$@"; do echo "import \"$i\""; done
        echo
        sed "1,/^\$/d; s/HOST\\./$host./g; s/AUX/$aux/g" "$here/src/script_eval.tmpl"
    } > "$here/src/$out"
}
gen Engine ParserGrammar script_engine.ab script.ab engine.ab grammar.ab host_parser.ab
gen Lexer Atn script_lexer.ab script.ab atn.ab lexer.ab host_lexer.ab
